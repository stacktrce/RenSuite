def detect_language() -> str:
    candidates = [os.environ.get("RENPY_SUITE_LANG", "")]
    if sys.platform == "win32":
        try:
            import ctypes
            lang_id = ctypes.windll.kernel32.GetUserDefaultUILanguage()
            candidates.append(locale.windows_locale.get(lang_id, ""))
        except (AttributeError, OSError):
            pass
    for var in ("LC_ALL", "LC_MESSAGES", "LANGUAGE", "LANG"):
        candidates.append(os.environ.get(var, ""))
    try:
        candidates.append(locale.getlocale()[0] or "")
    except ValueError:
        pass
    for c in candidates:
        code = c.replace("-", "_").split("_")[0].split(":")[0].lower()
        if code in STRINGS:
            return code
    return "en"


_language = detect_language()


def set_language(code: str):
    """Switch language; ``"system"`` follows the operating system."""
    global _language
    if code == "system":
        _language = detect_language()
    elif code in STRINGS:
        _language = code


def current_language() -> str:
    return _language


def languages() -> list:
    """``[(code, native name), …]`` of all available languages."""
    return [(code, strings["language_name"]) for code, strings in STRINGS.items()]


def t(key: str, **kwargs) -> str:
    text = STRINGS[_language].get(key) or STRINGS["en"].get(key, key)
    return text.format(**kwargs) if kwargs else text
